/**
 * Computes mock manager statistics matching the PostgreSQL get_manager_stats RPC function.
 */
export function getMockManagerStats(companyId?: string): ManagerStatsSummary {
  const targetCompanyId = companyId || MOCK_COMPANY.id;
  const activeWorkers = MOCK_WORKERS.filter(w => (!w.company_id || w.company_id === targetCompanyId) && w.status === 'ACTIVE').length;
  const activeBands = MOCK_BANDS.filter(b => (!b.company_id || b.company_id === targetCompanyId) && (b.status === 'ACTIVE' || b.status === 'WARNING')).length;
  const activeShifts = MOCK_SHIFTS.filter(s => (!s.company_id || s.company_id === targetCompanyId) && s.status === 'ACTIVE').length;
  const readingsToday = MOCK_READINGS.filter(r => !r.company_id || r.company_id === targetCompanyId).length;
  const openAlerts = MOCK_ALERTS.filter(a => (!a.company_id || a.company_id === targetCompanyId) && a.status === 'OPEN').length;

  return {
    active_workers: activeWorkers,
    active_bands: activeBands,
    active_shifts: activeShifts,
    readings_today: readingsToday,
    open_alerts: openAlerts,
  };
}

